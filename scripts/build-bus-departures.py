#!/usr/bin/env python3
"""
Builds server/data/bus_departures.sql: for every bus stop, route and direction, the departure
times from the RTA GTFS timetable, for weekdays (Mon-Fri) and weekends (Sat-Sun).
Loaded into the server database (D1) by the deploy workflow; the app asks /api/departures.

Usage: python3 scripts/build-bus-departures.py path/to/gtfs_folder_or_zip
"""
import csv, io, os, sys, zipfile, collections, hashlib

def open_feed(path):
    if os.path.isdir(path):
        return lambda n: open(os.path.join(path, n), encoding="utf-8-sig", newline="")
    z = zipfile.ZipFile(path); names = {os.path.basename(n): n for n in z.namelist()}
    return lambda n: io.TextIOWrapper(z.open(names[n]), encoding="utf-8-sig", newline="")

def main(src, dst):
    rd = open_feed(src)
    routes = {r["route_id"]: r for r in csv.DictReader(rd("routes.txt")) if r["route_type"] == "3"}
    cal = {c["service_id"]: c for c in csv.DictReader(rd("calendar.txt"))}
    trips = {}
    for t in csv.DictReader(rd("trips.txt")):
        if t["route_id"] not in routes: continue
        c = cal.get(t["service_id"]) or {}
        dts = [dt for dt, day in (("wd", "monday"), ("we", "saturday")) if c.get(day) == "1"]
        if dts: trips[t["trip_id"]] = (routes[t["route_id"]]["route_short_name"], int(t["direction_id"] or 0), t["trip_headsign"].strip(), dts)
    dep = collections.defaultdict(lambda: {"wd": set(), "we": set(), "head": collections.Counter()})
    last_stop = {}
    for r in csv.DictReader(rd("stop_times.txt")):
        t = trips.get(r["trip_id"])
        if not t: continue
        tm = r["departure_time"] or r["arrival_time"]
        try: h, m, _ = tm.split(":"); mins = int(h) * 60 + int(m)
        except ValueError: continue
        k = (r["stop_id"], t[0], t[1])
        for dt in t[3]: dep[k][dt].add(mins)
        dep[k]["head"][t[2]] += 1
        seq = int(r["stop_sequence"])
        if seq >= last_stop.get(r["trip_id"], (-1, None))[0]: last_stop[r["trip_id"]] = (seq, k)
    # the last stop of a trip is an arrival, not a departure
    ends = collections.Counter(k for _, k in last_stop.values())
    rows = []
    for (stop, route, d), v in dep.items():
        if ends[(stop, route, d)] >= sum(v["head"].values()) * 0.9: continue
        enc = lambda xs: ",".join(str(x) for x in sorted(xs))
        rows.append((stop, route, d, " ".join(v["head"].most_common(1)[0][0].split()), enc(v["wd"]), enc(v["we"])))
    rows.sort()
    esc = lambda s: "'" + str(s).replace("'", "''") + "'"
    body = []
    for i in range(0, len(rows), 50):
        body.append("INSERT INTO bus_dep (stop, route, dir, headsign, wd, we) VALUES\n" +
                    ",\n".join(f"({esc(a)},{esc(b)},{c},{esc(h)},{esc(w)},{esc(e)})" for a, b, c, h, w, e in rows[i:i + 50]) + ";")
    content = "\n".join(body)
    version = hashlib.sha256(content.encode()).hexdigest()[:16]
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(dst, "w", encoding="utf-8") as f:
        f.write(f"-- RTA bus departures per stop (generated by scripts/build-bus-departures.py)\n")
        f.write("DELETE FROM bus_dep;\n" + content + "\n")
        f.write(f"INSERT OR REPLACE INTO meta (k, v) VALUES ('bus_dep', '{version}');\n")
    with open(dst + ".version", "w") as f: f.write(version)
    print(f"{len(rows)} stop/route/direction rows, {os.path.getsize(dst) // 1024} KB, version {version} -> {dst}")

if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "..", "server", "data", "bus_departures.sql"))
