// Stamps the version from package.json into every place that needs it.
// Runs automatically with `npm version patch|minor|major`, and before every build.
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const v = pkg.version;
const [maj, min, pat] = v.split('.').map(n => parseInt(n, 10) || 0);
const code = maj * 10000 + min * 100 + pat;            // 1.2.0 -> 10200 (Android versionCode)
const edit = (rel, fn) => { const f = path.join(root, rel); if (fs.existsSync(f)) { fs.writeFileSync(f, fn(fs.readFileSync(f, 'utf8'))); console.log('  stamped', rel); } };

fs.writeFileSync(path.join(root, 'www/version.js'),
  `// Generated by scripts/version.js. Do not edit.\nself.APP_VERSION = ${JSON.stringify(v)};\nself.APP_BUILD = ${code};\n`);
console.log(`Metro Alert v${v} (build ${code})`);

edit('www/manifest.webmanifest', s => { const m = JSON.parse(s); m.version = v; return JSON.stringify(m, null, 2) + '\n'; });
edit('www/sw.js', s => s.replace(/const VERSION = '[^']*';/, `const VERSION = '${v}';`));
edit('android/app/build.gradle', s => s
  .replace(/versionCode \d+/, `versionCode ${code}`)
  .replace(/versionName "[^"]*"/, `versionName "${v}"`));
edit('ios/App/App.xcodeproj/project.pbxproj', s => s
  .replace(/MARKETING_VERSION = [^;]+;/g, `MARKETING_VERSION = ${v};`)
  .replace(/CURRENT_PROJECT_VERSION = [^;]+;/g, `CURRENT_PROJECT_VERSION = ${code};`));
